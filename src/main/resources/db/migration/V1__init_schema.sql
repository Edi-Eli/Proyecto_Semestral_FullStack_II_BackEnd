-- ---------------------------------------------------------------
-- Módulo: usuario (roles + usuarios)
-- ---------------------------------------------------------------
CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(50)  NOT NULL UNIQUE,
    descripcion VARCHAR(200)
);

CREATE TABLE usuarios (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_id              BIGINT       NOT NULL REFERENCES roles (id),
    run                 VARCHAR(20)  NOT NULL UNIQUE,
    correo              VARCHAR(100) NOT NULL UNIQUE,
    password_hash       VARCHAR(100) NOT NULL,
    nombre              VARCHAR(50)  NOT NULL,
    apellidos           VARCHAR(100) NOT NULL,
    fecha_nacimiento    DATE,
    telefono            VARCHAR(20),
    region              VARCHAR(100),
    comuna              VARCHAR(100),
    direccion           VARCHAR(300),
    preferencia_entrega VARCHAR(20),          -- RETIRO | DESPACHO
    cuenta_corriente    BOOLEAN      NOT NULL DEFAULT FALSE,
    activo              BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_creacion      TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    fecha_actualizacion TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    CONSTRAINT chk_usuarios_preferencia
        CHECK (preferencia_entrega IS NULL OR preferencia_entrega IN ('RETIRO', 'DESPACHO'))
);

CREATE INDEX idx_usuarios_rol    ON usuarios (rol_id);
CREATE INDEX idx_usuarios_activo ON usuarios (activo);

-- ---------------------------------------------------------------
-- Módulo: producto (categorías, subcategorías, productos)
-- ---------------------------------------------------------------
CREATE TABLE categorias (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(80) NOT NULL UNIQUE,
    imagen_url VARCHAR(255)
);

CREATE TABLE subcategorias (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT      NOT NULL REFERENCES categorias (id),
    nombre       VARCHAR(80) NOT NULL,
    CONSTRAINT uq_subcategorias_categoria_nombre UNIQUE (categoria_id, nombre)
);

CREATE INDEX idx_subcategorias_categoria ON subcategorias (categoria_id);

CREATE TABLE productos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(20)   NOT NULL UNIQUE,
    subcategoria_id     BIGINT        NOT NULL REFERENCES subcategorias (id),
    nombre              VARCHAR(150)  NOT NULL,
    descripcion         TEXT,
    marca               VARCHAR(80),
    unidad              VARCHAR(30),
    precio_compra       DECIMAL(10, 2) NOT NULL CHECK (precio_compra >= 0),
    precio_venta        DECIMAL(10, 2) NOT NULL CHECK (precio_venta >= 0),
    en_oferta           BOOLEAN       NOT NULL DEFAULT FALSE,
    precio_oferta       DECIMAL(10, 2) CHECK (precio_oferta IS NULL OR precio_oferta >= 0),
    stock               INTEGER       NOT NULL DEFAULT 0 CHECK (stock >= 0),
    stock_minimo        INTEGER       NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    imagen_url          VARCHAR(500),
    activo              BOOLEAN       NOT NULL DEFAULT TRUE,
    fecha_creacion      TIMESTAMP     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    fecha_actualizacion TIMESTAMP     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE INDEX idx_productos_subcategoria ON productos (subcategoria_id);
CREATE INDEX idx_productos_activo       ON productos (activo);
CREATE INDEX idx_productos_en_oferta    ON productos (en_oferta);

-- ---------------------------------------------------------------
-- Módulo: carrito (persistente por usuario)
-- ---------------------------------------------------------------
CREATE TABLE carritos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT    NOT NULL UNIQUE REFERENCES usuarios (id) ON DELETE CASCADE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TABLE carrito_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrito_id      BIGINT        NOT NULL REFERENCES carritos (id) ON DELETE CASCADE,
    producto_id     BIGINT        NOT NULL REFERENCES productos (id),
    nombre          VARCHAR(150)  NOT NULL,          -- snapshot
    precio_unitario DECIMAL(10, 2) NOT NULL,         -- snapshot
    cantidad        INTEGER       NOT NULL CHECK (cantidad > 0),
    imagen_url      VARCHAR(500),
    CONSTRAINT uq_carrito_items_carrito_producto UNIQUE (carrito_id, producto_id)
);

CREATE INDEX idx_carrito_items_carrito ON carrito_items (carrito_id);

-- ---------------------------------------------------------------
-- Módulo: pedido (pedidos + items) con snapshots para la boleta
-- ---------------------------------------------------------------
CREATE TABLE pedidos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(30)  NOT NULL UNIQUE,   -- ORDER<timestamp>
    nro                 VARCHAR(20)  NOT NULL,          -- YYYYMMDDHHMMSS
    usuario_id          BIGINT       NOT NULL REFERENCES usuarios (id),
    cliente_nombre      VARCHAR(50)  NOT NULL,
    cliente_apellidos   VARCHAR(100) NOT NULL,
    cliente_correo      VARCHAR(100) NOT NULL,
    direccion_calle     VARCHAR(300),
    direccion_depto     VARCHAR(100),
    region              VARCHAR(100),
    comuna              VARCHAR(100),
    indicaciones        VARCHAR(300),
    tipo_entrega        VARCHAR(20)  NOT NULL,          -- RETIRO | DESPACHO
    metodo_pago         VARCHAR(20)  NOT NULL,          -- CONTADO | CUENTA_CORRIENTE
    estado              VARCHAR(20)  NOT NULL,          -- PENDIENTE|APROBADA|DESPACHADA|ENTREGADA|PAGADA|RECHAZADA
    total               DECIMAL(10, 2) NOT NULL CHECK (total >= 0),
    fecha_creacion      TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    fecha_actualizacion TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    CONSTRAINT chk_pedidos_tipo_entrega CHECK (tipo_entrega IN ('RETIRO', 'DESPACHO')),
    CONSTRAINT chk_pedidos_metodo_pago  CHECK (metodo_pago IN ('CONTADO', 'CUENTA_CORRIENTE')),
    CONSTRAINT chk_pedidos_estado       CHECK (estado IN
        ('PENDIENTE', 'APROBADA', 'DESPACHADA', 'ENTREGADA', 'PAGADA', 'RECHAZADA'))
);

CREATE INDEX idx_pedidos_usuario ON pedidos (usuario_id);
CREATE INDEX idx_pedidos_estado  ON pedidos (estado);

CREATE TABLE pedido_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT         NOT NULL REFERENCES pedidos (id) ON DELETE CASCADE,
    producto_id     BIGINT         NOT NULL REFERENCES productos (id),
    nombre          VARCHAR(150)   NOT NULL,          -- snapshot
    precio_unitario DECIMAL(10, 2) NOT NULL,          -- snapshot
    cantidad        INTEGER        NOT NULL CHECK (cantidad > 0),
    subtotal        DECIMAL(10, 2) NOT NULL CHECK (subtotal >= 0)
);

CREATE INDEX idx_pedido_items_pedido   ON pedido_items (pedido_id);
CREATE INDEX idx_pedido_items_producto ON pedido_items (producto_id);

-- ---------------------------------------------------------------
-- Módulo: cuenta (cuentas corrientes + movimientos)
-- ---------------------------------------------------------------
CREATE TABLE cuentas_corrientes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id     BIGINT         NOT NULL UNIQUE REFERENCES usuarios (id) ON DELETE CASCADE,
    limite_credito DECIMAL(10, 2) NOT NULL DEFAULT 0 CHECK (limite_credito >= 0),
    saldo_actual   DECIMAL(10, 2) NOT NULL DEFAULT 0,
    activa         BOOLEAN        NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP      NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TABLE movimientos_cuenta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id       BIGINT         NOT NULL REFERENCES cuentas_corrientes (id) ON DELETE CASCADE,
    tipo            VARCHAR(10)    NOT NULL,          -- CARGO | ABONO
    pedido_id       BIGINT         REFERENCES pedidos (id),
    descripcion     VARCHAR(200),
    monto           DECIMAL(10, 2) NOT NULL CHECK (monto > 0),
    saldo_posterior DECIMAL(10, 2) NOT NULL,
    fecha           TIMESTAMP      NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    CONSTRAINT chk_movimientos_tipo CHECK (tipo IN ('CARGO', 'ABONO'))
);

CREATE INDEX idx_movimientos_cuenta  ON movimientos_cuenta (cuenta_id);
CREATE INDEX idx_movimientos_pedido  ON movimientos_cuenta (pedido_id);

-- ---------------------------------------------------------------
-- Módulo: contacto (CR mínimo de mensajes)
-- ---------------------------------------------------------------
CREATE TABLE mensajes_contacto (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(100) NOT NULL,
    correo         VARCHAR(100) NOT NULL,
    mensaje        TEXT         NOT NULL,
    estado         VARCHAR(20)  NOT NULL DEFAULT 'NUEVO',   -- NUEVO | LEIDO | RESUELTO
    fecha_creacion TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    CONSTRAINT chk_mensajes_estado CHECK (estado IN ('NUEVO', 'LEIDO', 'RESUELTO'))
);

CREATE INDEX idx_mensajes_estado ON mensajes_contacto (estado);
